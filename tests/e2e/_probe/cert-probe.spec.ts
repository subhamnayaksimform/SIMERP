import fs from 'fs';
import { test } from '../../fixtures/auth';
const OUT = 'reports/results/2026-11-16-t1685/probe';
test('probe group-by views', async ({ primaryPage: p, empPage }) => {
  test.setTimeout(180_000);
  fs.mkdirSync(OUT, { recursive: true });
  const dump = async (name: string) => fs.writeFileSync(`${OUT}/${name}.yaml`, await p.locator('main').first().ariaSnapshot());
  await p.goto('/employee/certifications?tab=organisation&groupBy=certificate');
  await p.getByText(/Showing \d+ - \d+ of \d+ results/).waitFor();
  await dump('org-groupby-certificate');
  fs.writeFileSync(`${OUT}/rows-certificate.json`, JSON.stringify(await p.locator('table tbody tr').evaluateAll(trs => trs.slice(0, 8).map(tr => Array.from(tr.querySelectorAll('td')).map(td => (td as HTMLElement).innerText.trim()))), null, 1));
  await p.getByRole('button', { name: /^Show or hide the holders of / }).first().click();
  await p.waitForLoadState('networkidle');
  await dump('org-groupby-certificate-expanded');
  await p.goto('/employee/certifications?tab=organisation');
  await p.getByText(/Showing \d+ - \d+ of \d+ results/).waitFor();
  await dump('org-flat');
  await p.getByRole('button', { name: 'Filter by Department' }).click();
  fs.writeFileSync(`${OUT}/dept-popover.yaml`, await p.locator('[data-radix-popper-content-wrapper]').last().ariaSnapshot());
  await p.keyboard.press('Escape');
  await p.getByRole('button', { name: 'Filter by Status' }).click();
  fs.writeFileSync(`${OUT}/status-popover.yaml`, await p.locator('[data-radix-popper-content-wrapper]').last().ariaSnapshot());
  await p.keyboard.press('Escape');
  await p.goto('/employee/certifications');
  await p.getByText(/Showing \d+ - \d+ of \d+ results/).waitFor();
  await p.getByRole('button', { name: 'Filter by Status' }).click();
  fs.writeFileSync(`${OUT}/mine-status-popover.yaml`, await p.locator('[data-radix-popper-content-wrapper]').last().ariaSnapshot());
  await p.keyboard.press('Escape');
  await empPage.goto('/employee/certifications');
  await empPage.getByText(/Showing \d+ - \d+ of \d+ results/).waitFor();
  fs.writeFileSync(`${OUT}/emp-mine.yaml`, await empPage.locator('main').first().ariaSnapshot());
});
